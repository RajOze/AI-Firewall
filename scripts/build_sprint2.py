    async def generate_advisory(self, context: dict[str, Any]) -> ThreatAdvisory:
        start = time.perf_counter()

        fusion_score = float(context.get("fusion_risk_score", 0.0))
        anomaly_score = float(context.get("anomaly_score", 0.0))
